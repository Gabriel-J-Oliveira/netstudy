const assert = require('node:assert/strict');
const terminal = require('./integrated-lab-terminal.js');
const model = require('./integrated-lab-model.js');
const simulator = require('./integrated-lab-simulator.js');
const {PRESETS} = require('./integrated-lab-presets.js');
const load = id => model.importScenario(PRESETS.find(p=>p.id===id).scenario);
const run = restored => simulator.simulate(model.adapt(restored.state,restored.sourceId,restored.destinationId).input);
const freeze = o => { if (o && typeof o==='object') { Object.values(o).forEach(freeze); Object.freeze(o); } return o; };
let restored = load('two-networks-router');
for (const d of Object.values(restored.state.devices)) if (['router','switch'].includes(d.type)) restored.state = model.setProfile(restored.state,d.id,'cisco-ios').state;
let state = restored.state;
const result = run({...restored,state}); assert.equal(result.status,'success');
const sw = Object.values(state.devices).find(d=>d.type==='switch'), router = Object.values(state.devices).find(d=>d.type==='router');
let session = terminal.createSession(sw);
const execute = (s,c,b=state) => terminal.execute(s,c,b);
const out = (s,c,b=state) => { const r=execute(s,c,b); assert.equal(r.error,null,c); return r.output.join('\n'); };
assert.equal(session.prompt,`${sw.name}>`);
assert.match(out(session,'?'),/enable/);
assert.ok(!out(session,'?').includes('show running-config'));
assert.equal(execute(session,'show running-config').error.code,'wrong-mode');
session=execute(session,'enable').session;
assert.equal(session.mode,'privileged'); assert.equal(session.prompt,`${sw.name}#`);
assert.match(out(session,'?'),/disable/); assert.match(out(session,'show ?'),/show interfaces trunk/);
assert.ok(!out(session,'show ?').includes('show ip route'));
assert.match(out(session,'show interfaces ?'),/show interfaces status/);
assert.equal(execute(session,'sh int').error.code,'unknown-command','no ambiguous/partial abbreviations');
assert.equal(execute(session,'show ip route').error.code,'invalid-input');
assert.equal(execute(session,'configure terminal').session.mode,'config');
assert.equal(execute(session,'enable x').error.code,'unexpected-arguments');
assert.match(out(session,'show interfaces'),/GigabitEthernet1\/0\/1 is up, line protocol is up/);
assert.match(out(session,'show interfaces status'),/connected/);
assert.match(out(session,'show vlan brief'),/10\s+VLAN0010\s+active/);
assert.match(out(session,'show running-config'),/switchport access vlan 10/);
assert.match(out(session,'show arp'),/sem interface IP\/SVI/);
const initial={...state,observation:result.events[0]}, final={...state,observation:result.events.at(-1)};
assert.match(out(session,'show mac address-table',initial),/criterion: 0/);
const learned=result.events.at(-1).tables.mac.filter(r=>r.switchId===sw.id);
assert.ok(learned.length>0);
for(const row of learned) assert.ok(out(session,'show mac address-table',final).includes(model.interfaceName(state,row.interfaceId)));
assert.match(out(session,'show mac address-table',final),new RegExp(`criterion: ${learned.length}`));
assert.match(out(session,'show mac address-table',state),/criterion: 0/,'absent event does not use final future cache');
let changed = model.configure(state,sw.id,{vlans:{[sw.interfaces[0]]:30},allowedVlans:[30]}).state;
assert.match(out(session,'show running-config',changed),/switchport access vlan 30/);
assert.match(out(session,'show vlan brief',changed),/30\s+VLAN0030/);
changed={...changed,connections:changed.connections.filter(c=>c.a!==sw.interfaces[0] && c.b!==sw.interfaces[0])};
assert.match(out(session,'show interfaces',changed),/GigabitEthernet1\/0\/1 is down, line protocol is down/);
assert.match(out(session,'show running-config',changed),/no shutdown/);
let renamed=model.renameDevice(state,sw.id,'SW-1').state;
assert.equal(execute(session,'help',renamed).session.prompt,'SW-1#');
let userMode=execute(session,'disable').session; assert.equal(userMode.prompt,`${sw.name}>`);
assert.equal(execute(userMode,'exit').session.closed,true);
let rs=terminal.createSession(router);
rs=execute(rs,'enable').session;
assert.equal(rs.prompt,`${router.name}#`);
assert.match(out(rs,'show ip interface brief'),/GigabitEthernet0\/0\s+192\.168\.10\.1\s+YES manual up\s+up/);
assert.match(out(rs,'show ip route'),/C\s+192\.168\.20\.0\/24 is directly connected, GigabitEthernet0\/1/);
assert.match(out(rs,'show ip route'),/L\s+192\.168\.10\.1\/32/);
assert.match(out(rs,'show running-config'),/ip address 192\.168\.20\.1 255\.255\.255\.0/);
assert.equal(execute(rs,'show vlan brief').error.code,'invalid-input');
assert.ok(!out(rs,'show arp',initial).includes('192.168.20.20'));
const arp=result.events.at(-1).tables.arp.filter(r=>r.owner===router.id);
assert.ok(arp.length>0);
for(const row of arp) assert.ok(out(rs,'show arp',final).includes(row.ip));
let disconnected={...state,connections:state.connections.filter(c=>c.a!==router.interfaces[1] && c.b!==router.interfaces[1])};
assert.ok(!out(rs,'show ip route',disconnected).includes('192.168.20.0/24'));
assert.match(out(rs,'show ip interface brief',disconnected),/GigabitEthernet0\/1.*down\s+down/);
const cfg={...router.config.eth1,ip:'172.16.8.1',mask:'255.255.255.0'};
changed=model.configure(state,router.id,{eth1:cfg}).state;
assert.match(out(rs,'show ip route',changed),/172\.16\.8\.0\/24/);
assert.ok(!out(rs,'show ip route',changed).includes('192.168.20.0/24'));
assert.match(out(rs,'show interfaces',changed),/Internet address is 172\.16\.8\.1\/24/);
const before=JSON.stringify(final); out(rs,'show arp',freeze(final)); assert.equal(JSON.stringify(final),before);
restored=load('switch-trunk'); state=restored.state;
for(const d of Object.values(state.devices)) if(d.type==='switch') state=model.setProfile(state,d.id,'cisco-ios').state;
const trunkSwitch=state.devices.sw1, ts=terminal.createSession(trunkSwitch);
assert.match(out(ts,'show interfaces trunk'),/802\.1q\s+trunking/);
assert.match(out(ts,'show interfaces trunk'),/10,20/);
changed=model.configure(state,'sw1',{allowedVlans:[20]}).state;
assert.match(out(ts,'show interfaces trunk',changed),/GigabitEthernet1\/0\/5\s+20/);
assert.match(out(ts,'show interfaces trunk',changed),/não garante permissão/);
changed={...state,connections:state.connections.filter(c=>c.a!=='sw1:gi0/5' && c.b!=='sw1:gi0/5')};
assert.match(out(ts,'show interfaces trunk',changed),/Nenhum trunk operacional/);
assert.equal(terminal.parse('?').name,'?');
for(const profile of ['generic','dell-os10']) {
 const b=model.addDevice(model.createEmpty(),'switch',profile).state,d=Object.values(b.devices)[0];
 assert.equal(terminal.execute(terminal.createSession(d),'show interfaces',b).error.code,profile==='dell-os10'?'invalid-input':'unknown-command');
}

// Percurso de configuração em switch; cada comando devolve uma bancada nova.
restored=load('switch-trunk'); state=restored.state;
for(const d of Object.values(state.devices))if(d.type==='switch')state=model.setProfile(state,d.id,'cisco-ios').state;
let sw1=state.devices.sw1, cfgSession=terminal.createSession(sw1);
let step=execute(cfgSession,'enable');cfgSession=step.session;
step=execute(cfgSession,'configure terminal');cfgSession=step.session;
assert.equal(cfgSession.prompt,'SW1(config)#');
step=execute(cfgSession,'interface GigabitEthernet1/0/1');cfgSession=step.session;
assert.equal(cfgSession.mode,'config-if');assert.equal(cfgSession.prompt,'SW1(config-if)#');
step=execute(cfgSession,'description Link to PC-A',state);assert.equal(step.error,null);state=step.bench;
step=execute(step.session,'switchport access vlan 30',state);assert.equal(step.error,null);state=step.bench;
assert.equal(state.devices.sw1.config.vlans['sw1:gi0/1'],30);
assert.equal(state.interfaces['sw1:gi0/1'].mode,'access');
let showPriv=execute(step.session,'end',state).session;
assert.match(out(showPriv,'show running-config',state),/description Link to PC-A/);
assert.match(out(showPriv,'show running-config',state),/switchport access vlan 30/);
step=execute(step.session,'shutdown',state);state=step.bench;
assert.equal(state.devices.sw1.config.portSettings['sw1:gi0/1'].shutdown,true);
assert.ok(model.adapt(state,'pc-a','pc-b').input.connections.every(c=>!c.a.includes('sw1:gi0/1')&&!c.b.includes('sw1:gi0/1')));
step=execute(step.session,'no shutdown',state);state=step.bench;
assert.equal(state.devices.sw1.config.portSettings['sw1:gi0/1'].shutdown,false);
step=execute(step.session,'end',state);cfgSession=step.session;
assert.equal(cfgSession.mode,'privileged');assert.equal(cfgSession.prompt,'SW1#');
step=execute(cfgSession,'configure terminal',state);cfgSession=step.session;
step=execute(cfgSession,'hostname SW-1',state);state=step.bench;cfgSession=step.session;
assert.equal(state.devices.sw1.name,'SW-1');assert.equal(cfgSession.prompt,'SW-1(config)#');
step=execute(cfgSession,'interface GigabitEthernet1/0/5',state);cfgSession=step.session;
step=execute(cfgSession,'switchport mode access',state);state=step.bench;
assert.equal(state.interfaces['sw1:gi0/5'].mode,'access');
// CLI settings survive Scenario Schema v1 save/load.
let schema=model.exportScenario(state,{name:'Cisco CLI'}),loaded=model.importScenario(schema);
assert.equal(loaded.state.devices.sw1.name,'SW-1');
assert.equal(loaded.state.devices.sw1.config.portSettings['sw1:gi0/1'].description,'Link to PC-A');
assert.equal(loaded.state.interfaces['sw1:gi0/5'].mode,'access');
assert.equal(loaded.state.devices.sw1.config.vlans['sw1:gi0/5'],10);
// Router address, no address, interface admin state and GUI-to-CLI synchronization.
restored=load('two-networks-router');state=restored.state;
for(const d of Object.values(state.devices))if(d.type==='router')state=model.setProfile(state,d.id,'cisco-ios').state;
const routerCisco=state.devices.r1;rs=terminal.createSession(routerCisco);rs=execute(rs,'enable',state).session;
rs=execute(rs,'configure terminal',state).session;rs=execute(rs,'interface GigabitEthernet0/1',state).session;
step=execute(rs,'ip address 192.168.30.1 255.255.255.0',state);state=step.bench;rs=execute(step.session,'end',state).session;
assert.equal(state.devices.r1.config.eth1.ip,'192.168.30.1');
assert.match(out(rs,'show running-config',state),/ip address 192.168.30.1 255.255.255.0/);
rs=execute(rs,'configure terminal',state).session;rs=execute(rs,'interface GigabitEthernet0/1',state).session;
step=execute(rs,'no ip address',state);state=step.bench;rs=execute(step.session,'end',state).session;
assert.equal(state.devices.r1.config.eth1.ip,'');
assert.match(out(rs,'show ip interface brief',state),/GigabitEthernet0\/1\s+unassigned/);
rs=execute(rs,'configure terminal',state).session;rs=execute(rs,'interface GigabitEthernet0/1',state).session;
step=execute(rs,'shutdown',state);state=step.bench;rs=step.session;
assert.equal(state.devices.r1.config.portSettings['r1:eth1'].shutdown,true);
schema=model.exportScenario(state,{name:'R1 CLI'});loaded=model.importScenario(schema);
assert.equal(loaded.state.devices.r1.config.eth1.ip,'');
assert.equal(loaded.state.devices.r1.config.portSettings['r1:eth1'].shutdown,true);
// GUI configuration uses the same source consumed by show running-config.
state=model.configure(state,'r1',{eth1:{ip:'192.168.20.254',mask:'255.255.255.0'}}).state;
const guiPriv=execute(rs,'end',state).session;
assert.match(out(guiPriv,'show running-config',state),/ip address 192.168.20.254 255.255.255.0/);
const routerConfig=execute(guiPriv,'configure terminal',state).session,routerIf=execute(routerConfig,'interface GigabitEthernet0/1',state).session;
assert.equal(execute(routerIf,'ip address 999.1.1.1 255.0.0.0',state).error.code,'invalid-input');
assert.equal(execute(routerConfig,'interface BadPort',state).error.code,'invalid-input');
assert.match(out(routerConfig,'?',state),/hostname <nome>/);
console.log('Cisco IOS-like v1: modos, configuração bidirecional, GUI, persistência e consultas sincronizadas aprovados.');
