const assert = require("node:assert/strict");
const terminal = require("./integrated-lab-terminal.js");
const model = require("./integrated-lab-model.js");
const simulator = require("./integrated-lab-simulator.js");
const {PRESETS} = require("./integrated-lab-presets.js");

const scenario = PRESETS.find(item => item.id === "switch-trunk").scenario;
const restored = model.importScenario(scenario);
let state = model.setProfile(restored.state, "sw1", "dell-os10").state;
let session = terminal.createSession(state.devices.sw1);
const run = (command, bench = state) => {
  const result = terminal.execute(session, command, bench);
  session = result.session;
  if (result.bench) state = result.bench;
  return result;
};
const output = (command, bench = state) => {
  const result = run(command, bench);
  assert.equal(result.error, null, `${command}: ${result.error?.message}`);
  return result.output.join("\n");
};
const simulate = () => simulator.simulate(model.adapt(state, restored.sourceId, restored.destinationId).input);
assert.equal(session.prompt, "SW1#");
assert.match(output("?"), /show interface status/);
assert.match(output("show interface status"), /ethernet1\/1\/1\s+up\s+access\s+10/);
assert.match(output("show interface"), /ethernet1\/1\/5 is up.*\n  Layer 2 mode trunk/);
assert.match(output("show vlan"), /VLAN10.*ethernet1\/1\/5.*ethernet1\/1\/1/);
assert.match(output("show running-configuration"), /interface ethernet1\/1\/5\n switchport mode trunk\n switchport trunk allowed vlan 10,20/);
assert.match(output("show ip interface brief"), /não possui interface IP\/SVI/);
assert.match(output("show mac address-table"), /Nenhuma entrada MAC/);
const event = simulate().events.at(-1);
assert.equal(simulate().status, "success");
assert.match(output("show mac address-table", {...state, observation: event}), /AA:AA:AA:AA:AA:AA.*ethernet1\/1\/1/);
assert.match(output("show mac address-table", {...state, observation: simulate().events[0]}), /Nenhuma entrada MAC/);

assert.equal(run("configure terminal").error, null);
assert.equal(session.prompt, "SW1(config)#");
assert.equal(run("interface ethernet1/1/5").error, null);
assert.equal(session.prompt, "SW1(conf-if-eth1/1/5)#");
assert.equal(run("switchport trunk allowed vlan 20").error, null);
assert.deepEqual(state.devices.sw1.config.allowedVlans, [20]);
assert.notEqual(simulate().status, "success", "allowed list bloqueia VLAN 10 no trunk");
assert.equal(run("switchport trunk allowed vlan 10,20").error, null);
assert.equal(simulate().status, "success");
assert.equal(run("shutdown").error, null);
assert.equal(state.devices.sw1.config.portSettings["sw1:gi0/5"].shutdown, true);
assert.match(output("end"), /^$/);
assert.match(output("show interface status"), /ethernet1\/1\/5\s+disabled/);
assert.notEqual(simulate().status, "success");
assert.equal(run("configure terminal").error, null);
assert.equal(run("interface ethernet1/1/5").error, null);
assert.equal(run("no shutdown").error, null);
assert.equal(simulate().status, "success");
assert.equal(run("switchport mode access").error, null);
assert.equal(state.interfaces["sw1:gi0/5"].mode, "access");
assert.equal(run("switchport access vlan 30").error, null);
assert.equal(state.devices.sw1.config.vlans["sw1:gi0/5"], 30);
assert.equal(run("switchport mode trunk").error, null);
assert.equal(simulate().status, "success");
assert.equal(run("exit").error, null);
assert.equal(session.mode, "config");
assert.equal(run("hostname Dell-Core").error, null);
assert.equal(state.devices.sw1.name, "Dell-Core");
assert.equal(session.prompt, "Dell-Core(config)#");
assert.equal(run("end").error, null);
assert.equal(session.prompt, "Dell-Core#");
assert.match(output("show running-configuration"), /hostname Dell-Core/);

const guiChanged = model.configure(state, "sw1", {allowedVlans: [10]}).state;
assert.match(output("show running-configuration", guiChanged), /switchport trunk allowed vlan 10\n/);
const saved = model.exportScenario(state, {sourceId: restored.sourceId, destinationId: restored.destinationId});
const loaded = model.importScenario(saved);
assert.equal(loaded.state.devices.sw1.profile, "dell-os10");
assert.equal(loaded.state.devices.sw1.name, "Dell-Core");
assert.deepEqual(loaded.state.devices.sw1.config.allowedVlans, [10, 20]);
assert.equal(loaded.state.devices.sw1.config.portSettings["sw1:gi0/5"].shutdown, false);
assert.equal(loaded.state.interfaces["sw1:gi0/5"].mode, "trunk");

const before = JSON.stringify(state);
assert.equal(run("interface ethernet1/1/1").error.code, "wrong-mode");
assert.equal(run("show vlan brief").error.code, "invalid-input");
assert.equal(run("configure terminal extra").error.code, "invalid-input");
assert.equal(run("configure terminal").error, null);
assert.equal(run("interface ethernet1/1/99").error.code, "invalid-input");
assert.equal(run("interface ethernet1/1/1").error, null);
assert.equal(run("switchport access vlan 0").error.code, "invalid-input");
assert.equal(run("switchport trunk allowed vlan 1-500").error.code, "invalid-input");
assert.equal(run("switchport access vlan 30").error, null);
const afterValid = JSON.stringify(state);
assert.equal(run("switchport trunk allowed vlan 1-500").error.code, "invalid-input");
assert.equal(run("switchport access vlan 4095").error.code, "invalid-input");
assert.notEqual(afterValid, before);
assert.equal(JSON.stringify(state), afterValid, "comandos inválidos preservam a bancada");
console.log("Dell OS10-like v1: consultas, eventos, configuração, simulador, GUI e persistência aprovados.");
