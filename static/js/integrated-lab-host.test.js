const assert = require('node:assert/strict');
const terminal = require('./integrated-lab-terminal.js');
const model = require('./integrated-lab-model.js');
const simulator = require('./integrated-lab-simulator.js');
const {PRESETS} = require('./integrated-lab-presets.js');

const scenario = PRESETS.find(item => item.id === 'basic-lan').scenario;
const restored = model.importScenario(scenario);
let state = model.setProfile(restored.state, restored.sourceId, 'windows').state;
state = model.setProfile(state, restored.destinationId, 'linux').state;
const windows = state.devices[restored.sourceId], linux = state.devices[restored.destinationId];
let ws = terminal.createSession(windows), ls = terminal.createSession(linux);
const run = (session, command, bench = state) => terminal.execute(session, command, bench);
const text = (session, command, bench = state) => {
  const result = run(session, command, bench);
  assert.equal(result.error, null, `${command}: ${result.error?.message}`);
  return result.output.join('\n');
};
assert.equal(ws.prompt, `C:\\Users\\${windows.name}>`);
assert.equal(ls.prompt, `${linux.name}:~$`);
assert.equal(text(ws, 'hostname'), windows.name);
assert.match(text(ws, 'ipconfig'), /Gateway Padrão/);
assert.match(text(ws, 'ipconfig /all'), /DHCP Habilitado.*Não/);
assert.match(text(ws, 'ipconfig /all'), new RegExp(windows.config.mac));
assert.match(text(ws, 'route print'), /Tabela de Rotas IPv4/);
assert.match(text(ws, 'arp -a'), /Nenhuma associação ARP/);
assert.match(text(ls, 'ip addr'), /inet 192\.168\.10\.20\/24/);
assert.match(text(ls, 'ip link'), /administrativamente ativa/);
assert.match(text(ls, 'ip route'), /192\.168\.10\.0\/24 dev eth0/);
assert.match(text(ls, 'ip neigh'), /Nenhuma associação ARP/);
assert.match(text(ws, 'ping 192.168.10.20'), /Echo Reply recebido/);
assert.match(text(ls, 'ping 192.168.10.10'), /Echo Reply recebido/);

const result = simulator.simulate(model.adapt(state, restored.sourceId, restored.destinationId).input);
assert.equal(result.status, 'success');
const event = result.events.at(-1);
assert.ok(event.tables.arp.some(row => row.owner === windows.id));
assert.match(text(ws, 'arp -a', {...state, observation: event}), /dinâmico/);
const reverse = simulator.simulate(model.adapt(state, restored.destinationId, restored.sourceId).input);
assert.equal(reverse.status, 'success');
assert.match(text(ls, 'ip neigh', {...state, observation: reverse.events.at(-1)}), /lladdr/);
assert.match(text(ws, 'arp -a', {...state, observation: result.events[0]}), /Nenhuma associação ARP/, 'cache follows selected event');

const before = JSON.stringify(state);
let changed = run(ws, 'netsh interface ipv4 set address name="Ethernet" static 192.168.10.77 255.255.255.0 192.168.10.1');
assert.equal(changed.error, null);
state = changed.bench; ws = changed.session;
assert.equal(state.devices[windows.id].config.ip, '192.168.10.77');
assert.equal(state.devices[windows.id].config.gateway, '192.168.10.1');
assert.equal(JSON.stringify(restored.state), JSON.stringify(model.importScenario(scenario).state));
assert.notEqual(JSON.stringify(state), before);
assert.match(text(ws, 'ipconfig /all'), /192\.168\.10\.77/);
assert.match(text(ws, 'route print'), /192\.168\.10\.1/);
assert.equal(run(ws, 'netsh interface ipv4 set address name=Ethernet static 999.1.1.1 255.255.255.0').error.code, 'invalid-address');
assert.equal(run(ws, 'netsh interface ipv4 set address name=WiFi static 192.168.10.77 255.255.255.0').error.code, 'invalid-input');
assert.equal(run(ws, 'ipconfig /bad').error.code, 'invalid-input');
assert.equal(run(ws, 'ip addr').error.code, 'unknown-command');

changed = run(ls, 'ip addr add 192.168.10.88/25 dev eth0');
assert.equal(changed.error, null); state = changed.bench; ls = changed.session;
assert.equal(state.devices[linux.id].config.mask, '255.255.255.128');
assert.match(text(ls, 'ip addr'), /192\.168\.10\.88\/25/);
changed = run(ls, 'ip route add default via 192.168.10.1 dev eth0');
assert.equal(changed.error, null); state = changed.bench; ls = changed.session;
assert.equal(state.devices[linux.id].config.gateway, '192.168.10.1');
assert.match(text(ls, 'ip route'), /default via 192\.168\.10\.1/);
changed = run(ls, 'ip link set eth0 down');
assert.equal(changed.error, null); state = changed.bench; ls = changed.session;
assert.equal(state.devices[linux.id].config.portSettings[linux.interfaces[0]].shutdown, true);
assert.match(text(ls, 'ip link'), /administrativamente desligada/);
assert.ok(model.adapt(state, windows.id, linux.id).input.connections.every(link => link.a !== linux.interfaces[0] && link.b !== linux.interfaces[0]));
const unavailable = simulator.simulate(model.adapt(state, windows.id, linux.id).input);
assert.notEqual(unavailable.status, 'success');
let saved = model.exportScenario(state, {name: 'Hosts por CLI', sourceId: windows.id, destinationId: linux.id});
let loaded = model.importScenario(saved);
assert.equal(loaded.state.devices[linux.id].config.portSettings[linux.interfaces[0]].shutdown, true);
assert.equal(loaded.state.devices[windows.id].config.ip, '192.168.10.77');
changed = run(ls, 'ip link set eth0 up'); state = changed.bench; ls = changed.session;
assert.equal(state.devices[linux.id].config.portSettings[linux.interfaces[0]].shutdown, false);
changed = run(ls, 'ip route del default'); state = changed.bench; ls = changed.session;
assert.equal(state.devices[linux.id].config.gateway, '');
changed = run(ls, 'ip addr del 192.168.10.88/25 dev eth0'); state = changed.bench; ls = changed.session;
assert.equal(state.devices[linux.id].config.ip, '');
assert.equal(state.devices[linux.id].config.mask, '');
assert.equal(run(ls, 'ip addr del 192.168.10.88/25 dev eth0').error.code, 'address-not-found');
assert.equal(run(ls, 'ip route del default').error.code, 'route-not-found');
assert.equal(run(ls, 'ip link set bad down').error.code, 'invalid-input');
assert.equal(run(ls, 'netsh interface ipv4 set address name=Ethernet static 192.168.10.88 255.255.255.0').error.code, 'unknown-command');
saved = model.exportScenario(state, {name: 'Host sem IPv4'});
loaded = model.importScenario(saved);
assert.equal(loaded.state.devices[linux.id].config.ip, '');
// A GUI grava o mesmo campo que as consultas do terminal leem.
state = model.configure(state, windows.id, {gateway: '192.168.10.254'}).state;
assert.match(text(ws, 'ipconfig'), /192\.168\.10\.254/);
state = model.configure(state, linux.id, {ip: '10.10.0.2', mask: '255.255.0.0', portSettings: {[linux.interfaces[0]]: {shutdown: true}}}).state;
assert.match(text(ls, 'ip addr'), /10\.10\.0\.2\/16/);
assert.match(text(ls, 'ip link'), /administrativamente desligada/);
console.log('Terminais Windows/Linux: consultas, cache por evento, configuração, GUI, simulação e persistência aprovados.');
