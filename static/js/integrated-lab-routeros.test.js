const assert = require("node:assert/strict");
const terminal = require("./integrated-lab-terminal.js");
const model = require("./integrated-lab-model.js");
const simulator = require("./integrated-lab-simulator.js");
const {PRESETS} = require("./integrated-lab-presets.js");

assert.deepEqual(terminal.parse("/IP address print"), {name: "/ip", args: ["address", "print"], empty: false});
assert.equal(terminal.parse("/ip;bad").error.code, "invalid-command");
const scenario = PRESETS.find(item => item.id === "two-networks-router").scenario;
const restored = model.importScenario(scenario);
let state = model.setProfile(restored.state, "r1", "mikrotik-routeros").state;
let session = terminal.createSession(state.devices.r1);
const run = (command, observation) => {
  const result = terminal.execute(session, command, observation ? {...state, observation} : state);
  session = result.session;
  if (result.bench) state = result.bench;
  return result;
};
const output = command => {
  const result = run(command);
  assert.equal(result.error, null, `${command}: ${result.error?.message}`);
  return result.output.join("\n");
};
const simulate = () => simulator.simulate(model.adapt(state, restored.sourceId, restored.destinationId).input);
assert.equal(session.prompt, "[admin@R1] >");
assert.match(output("help"), /\/interface/);
assert.match(output("/interface print"), /ether1.*10:10:10:10:10:10/);
assert.match(output("/interface ethernet print"), /ether2/);
assert.match(output("/ip address print"), /192\.168\.10\.1\/24.*ether1/);
assert.match(output("/ip address print"), /192\.168\.20\.1\/24.*ether2/);
assert.match(output("/ip route print"), /192\.168\.20\.0\/24.*ether2/);
assert.match(output("/ip arp print"), /Nenhuma associação ARP/);
assert.match(output("/system identity print"), /name: R1/);
assert.equal(simulate().status, "success");
const event = simulate().events.at(-1);
const arp = run("/ip arp print", event);
assert.equal(arp.error, null);
assert.match(arp.output.join("\n"), /192\.168\.20\.30.*ether2/);
const early = run("/ip arp print", simulate().events[0]);
assert.match(early.output.join("\n"), /Nenhuma associação ARP/);

assert.equal(run("/system identity set name=Core-R1").error, null);
assert.equal(state.devices.r1.name, "Core-R1");
assert.equal(session.prompt, "[admin@Core-R1] >");
assert.match(output("/system identity print"), /Core-R1/);
assert.equal(run("/interface set ether2 disabled=yes").error, null);
assert.equal(state.devices.r1.config.portSettings["r1:eth1"].shutdown, true);
assert.match(output("/interface print"), /X ether2/);
assert.doesNotMatch(output("/ip route print"), /192\.168\.20\.0\/24/);
assert.notEqual(simulate().status, "success");
assert.equal(run("/interface set ether2 disabled=no").error, null);
assert.equal(simulate().status, "success");

assert.equal(run("/ip address add address=192.168.20.2/24 interface=ether2").error.code, "address-exists");
assert.equal(run("/ip address remove 1").error, null);
assert.equal(state.devices.r1.config.eth1.ip, "");
assert.doesNotMatch(output("/ip address print"), /ether2/);
assert.doesNotMatch(output("/ip route print"), /192\.168\.20\.0\/24/);
assert.notEqual(simulate().status, "success", "sem endereço de saída a simulação falha de forma controlada");
assert.equal(model.importScenario(model.exportScenario(state)).state.devices.r1.config.eth1.ip, "", "interface sem IPv4 persiste no schema");
assert.equal(run("/ip address add address=192.168.20.1/24 interface=ether2").error, null);
assert.equal(state.devices.r1.config.eth1.mask, "255.255.255.0");
assert.equal(simulate().status, "success");
const guiChanged = model.configure(state, "r1", {eth0: {ip: "192.168.10.9"}}).state;
assert.match(terminal.execute(session, "/ip address print", guiChanged).output.join("\n"), /192\.168\.10\.9\/24.*ether1/, "edição pela GUI aparece na consulta CLI");

const saved = model.exportScenario(state, {sourceId: restored.sourceId, destinationId: restored.destinationId});
const loaded = model.importScenario(saved);
assert.equal(loaded.state.devices.r1.profile, "mikrotik-routeros");
assert.equal(loaded.state.devices.r1.name, "Core-R1");
assert.equal(loaded.state.devices.r1.config.eth1.ip, "192.168.20.1");
assert.equal(loaded.state.devices.r1.config.portSettings["r1:eth1"].shutdown, false);

const before = JSON.stringify(state);
assert.equal(run("/ip route add dst-address=10.0.0.0/8 gateway=192.168.10.2").error, null);
assert.match(output("/ip route print"), /10\.0\.0\.0\/8.*192\.168\.10\.2/);
assert.equal(run("/ip route remove 10.0.0.0/8").error, null);
assert.deepEqual(state.devices.r1.config.staticRoutes, [], "adicionar e remover rota limpa a tabela estática");
const beforeInvalid = JSON.stringify(state);
assert.equal(run("/ip route add dst-address=bad gateway=192.168.10.2").error.code, "invalid-input");
assert.equal(run("/ip address add address=999.1.1.1/24 interface=ether1").error.code, "invalid-address");
assert.equal(run("/ip address remove 9").error.code, "address-not-found");
assert.equal(run("/interface set ether9 disabled=yes").error.code, "interface-not-found");
assert.equal(run("/interface set ether1 disabled=maybe").error.code, "invalid-input");
assert.equal(run("/system identity set name=").error.code, "invalid-input");
assert.equal(run("/interface ethernet foo").error.code, "invalid-input");
assert.equal(JSON.stringify(state), beforeInvalid, "comandos inválidos preservam a bancada");
assert.equal(terminal.execute(session, "/ip address print", model.setProfile(state, "r1", "generic").state).error.code, "unknown-command");
console.log("RouterOS-like v1: consultas, ARP por evento, configuração, simulação, persistência e limites aprovados.");
