const assert=require('node:assert/strict');
const model=require('./integrated-lab-model.js');
const simulator=require('./integrated-lab-simulator.js');
const services=require('./integrated-lab-services.js');
const terminal=require('./integrated-lab-terminal.js');
const engine=require('./integrated-lab-exercise-engine.js');
const {PRESETS}=require('./integrated-lab-presets.js');
const apply=change=>{assert.equal(change.error,undefined,change.error);return change.state;};
const preset=PRESETS.find(item=>item.id==='lan-services');assert.ok(preset);
const restored=model.importScenario(preset.scenario);let state=restored.state;
assert.equal(simulator.simulate(model.adapt(state,'pc-a','pc-c').input).status,'success');
assert.equal(services.connect(state,'pc-a','app.lab','tcp',80).status,'success');
const renewed=services.renew(state,'pc-a');assert.equal(renewed.result.status,'success');
const unassigned=apply(model.configure(state,'pc-a',{ip:'',mask:'',gateway:'',dns:''}));
assert.equal(services.renew(unassigned,'pc-a').result.status,'success');
assert.deepEqual(renewed.result.events.map(event=>event.id),['dhcp-discover','dhcp-offer','dhcp-request','dhcp-ack']);
assert.equal(renewed.result.lease.ip,'192.168.10.100');
assert.equal(renewed.bench.devices['pc-a'].config.gateway,'192.168.10.1');
assert.equal(renewed.bench.devices['pc-a'].config.dns,'192.168.10.20');
assert.equal(renewed.bench.serviceRuntime.leases['pc-a'].leaseMinutes,60);
assert.equal(services.renew(renewed.bench,'pc-a').result.lease.ip,'192.168.10.100');
assert.equal(services.resolve(renewed.bench,'pc-a','app.lab').address,'192.168.20.30');
assert.equal(services.connect(renewed.bench,'pc-a','app.lab','tcp',80).status,'success');
assert.equal(services.connect(renewed.bench,'pc-a','app.lab','udp',5300).status,'success');
assert.equal(services.connect(renewed.bench,'pc-a','app.lab','tcp',5300).events.at(-1).id,'service-unavailable');
const exported=model.exportScenario(renewed.bench,{name:'Serviços',sourceId:'pc-a',destinationId:'pc-c'});
assert.equal(Object.hasOwn(exported,'serviceRuntime'),false);
assert.equal(Object.hasOwn(model.importScenario(exported).state,'serviceRuntime'),false);
assert.deepEqual(model.importScenario(exported).state.devices['pc-b'].config.dnsServer.records,[{name:'app.lab',address:'192.168.20.30'}]);
const malformed=structuredClone(exported);malformed.devices['pc-b'].config.dnsServer.records[0].address='999.1.1.1';
assert.throws(()=>model.importScenario(malformed),/Registro A inválido/);
const old=structuredClone(exported);for(const entry of Object.values(old.devices))if(entry.type==='pc')for(const key of ['dns','dhcpClient','dhcpServer','dnsServer','services'])delete entry.config[key];
assert.ok(model.importScenario(old).state.devices['pc-a']);

const noDhcp=apply(model.setHostServices(state,'pc-b',{dhcpServer:{...state.devices['pc-b'].config.dhcpServer,enabled:false}}));
assert.equal(services.renew(noDhcp,'pc-a').result.events.at(-1).id,'dhcp-timeout');
const badGateway=apply(model.setHostServices(state,'pc-b',{dhcpServer:{...state.devices['pc-b'].config.dhcpServer,gateway:'192.168.10.254'}}));
assert.equal(services.renew(badGateway,'pc-a').result.lease.gateway,'192.168.10.254');
assert.equal(services.connect(services.renew(badGateway,'pc-a').bench,'pc-a','app.lab','tcp',80).status,'failure');
const badDns=apply(model.setHostServices(state,'pc-a',{dns:'192.168.10.99'}));
assert.equal(services.resolve(badDns,'pc-a','app.lab').events.at(-1).id,'dns-unreachable');
const noRecord=apply(model.setHostServices(state,'pc-b',{dnsServer:{enabled:true,records:[]}}));
assert.equal(services.resolve(noRecord,'pc-a','app.lab').events.at(-1).id,'dns-no-record');
const dnsDown=apply(model.setHostServices(state,'pc-b',{dnsServer:{...state.devices['pc-b'].config.dnsServer,enabled:false}}));
assert.equal(services.resolve(dnsDown,'pc-a','app.lab').events.at(-1).id,'dns-unavailable');
const serviceDown=apply(model.setHostServices(state,'pc-c',{services:state.devices['pc-c'].config.services.map(service=>({...service,enabled:false}))}));
assert.equal(services.connect(serviceDown,'pc-a','app.lab','tcp',80).events.at(-1).id,'service-unavailable');
assert.ok(services.connect(serviceDown,'pc-a','app.lab','tcp',80).events.some(event=>event.id==='service-network-ok'));
const wrongVlan=apply(model.configure(state,'sw1',{vlans:{'sw1:gi0/3':20}}));
assert.equal(services.renew(wrongVlan,'pc-a').result.events.at(-1).id,'dhcp-timeout');
const shutdown=apply(model.configure(state,'pc-b',{portSettings:{'pc-b:eth0':{shutdown:true}}}));
assert.equal(services.renew(shutdown,'pc-a').result.events.at(-1).id,'dhcp-timeout');
const brokenRoute=apply(model.configure(state,'pc-a',{gateway:'192.168.10.254'}));
assert.equal(services.connect(brokenRoute,'pc-a','app.lab','tcp',80).events.at(-1).id,'service-network-failed');
const emptyPool=apply(model.setHostServices(state,'pc-b',{dhcpServer:{...state.devices['pc-b'].config.dhcpServer,poolStart:'192.168.10.20',poolEnd:'192.168.10.20'}}));
assert.equal(services.renew(emptyPool,'pc-a').result.events.at(-1).id,'dhcp-pool-empty');

let trunk=state;
const cable=trunk.connections.find(link=>[link.a,link.b].includes('pc-b:eth0'));
trunk=apply(model.disconnect(trunk,cable.id));
trunk=apply(model.connect(trunk,'sw1:gi0/5','sw2:gi0/5'));
trunk=apply(model.connect(trunk,'pc-b:eth0','sw2:gi0/3'));
assert.equal(services.renew(trunk,'pc-a').result.status,'success');
trunk=apply(model.configure(trunk,'sw2',{allowedVlans:[20]}));
assert.equal(services.renew(trunk,'pc-a').result.status,'failure');

let session=terminal.createSession(state.devices['pc-a']);
const exec=(command,bench)=>terminal.execute(session,command,bench);
let output=exec('ipconfig /all',state);assert.match(output.output.join('\n'),/DHCP Habilitado.*Sim/);
output=exec('ipconfig /renew',state);assert.equal(output.labResult.status,'success');state=output.bench;session=output.session;
assert.match(exec('ipconfig /all',state).output.join('\n'),/Lease \(duração\).*60/);
assert.equal(exec('nslookup app.lab',state).labResult.status,'success');
assert.equal(exec('curl http://app.lab',state).labResult.status,'success');
assert.equal(exec('connect udp app.lab 5300',state).labResult.status,'success');
state=apply(model.setProfile(state,'pc-a','linux'));session=terminal.createSession(state.devices['pc-a']);
assert.equal(exec('dhclient',state).labResult.status,'success');
assert.equal(exec('dig app.lab',state).labResult.status,'success');

const categories=new Set(),scenarios=new Set();
for(const difficulty of ['intermediate','advanced'])for(let seed=0;seed<50;seed++){
  const instance=engine.generateExercise('services',seed,{difficulty});
  assert.deepEqual(instance,engine.generateExercise('services',seed,{difficulty}));
  scenarios.add(JSON.stringify(instance.scenario));
  assert.ok(!Object.hasOwn(instance,'faults'));
  const broken=model.importScenario(instance.scenario).state,first=engine.validateExercise(instance,broken);
  assert.equal(first.complete,false);categories.add(first.category);
  const debug=engine.inspectExercise(instance);
  assert.equal(debug.faults.length,difficulty==='advanced'?2:1);
  assert.equal(engine.validateExercise(instance,debug.servicesBase).complete,true);
  const shortcut=apply(model.setHostServices(debug.servicesBase,'pc-a',{services:[{name:'Extra',protocol:'tcp',port:9999,enabled:true}]}));
  assert.equal(engine.validateExercise(instance,shortcut).category,'invariant');
  if(difficulty==='advanced'){
    let partial=broken;
    partial=apply(model.setHostServices(partial,'pc-a',{dns:debug.servicesBase.devices['pc-a'].config.dns}));
    partial=apply(model.setHostServices(partial,'pc-b',{dhcpServer:debug.servicesBase.devices['pc-b'].config.dhcpServer,dnsServer:debug.servicesBase.devices['pc-b'].config.dnsServer}));
    assert.equal(engine.validateExercise(instance,partial).category,'service-unavailable');
  }
}
assert.ok(scenarios.size>20);
for(const category of ['dhcp-unavailable','dhcp-options','dns-config','dns-record','service-unavailable'])assert.ok(categories.has(category),category);
console.log('Serviços: DORA, VLAN/trunk, DNS, TCP/UDP, CLI, Schema e troubleshooting aprovados.');
