const assert = require("node:assert/strict");
const terminal = require("./integrated-lab-terminal.js");
const model = require("./integrated-lab-model.js");
const profiles = require("./integrated-lab-profiles.js");
const frozen = value => { if (value && typeof value === "object") { Object.values(value).forEach(frozen); Object.freeze(value); } return value; };
assert.deepEqual(terminal.parse(" \t HELP  "), {name: "help", args: [], empty: false});
assert.deepEqual(terminal.parse("inspect 'duas palavras' \"\" C:\\Users"), {name: "inspect", args: ["duas palavras", "", "C:\\Users"], empty: false});
assert.equal(terminal.parse("   ").empty, true);
assert.equal(terminal.parse("help 'x").error.code, "unclosed-quote");
assert.equal(terminal.parse("help\nexit").error.code, "invalid-input");
assert.equal(terminal.parse("h".repeat(513)).error.code, "invalid-input");
assert.equal(terminal.parse(null).error.code, "invalid-input");
assert.equal(terminal.parse(";exit").error.code, "invalid-command");
let state = model.addDevice(model.createEmpty(), "pc", "linux").state;
state = model.addDevice(state, "pc", "windows").state;
const before = JSON.stringify(state);
let first = terminal.createSession(state.devices["pc-1"], profiles.get("pc", "linux"));
const second = terminal.createSession(state.devices["pc-2"]);
assert.equal(first.mode, "exec");
assert.deepEqual(first.context, {deviceId: "pc-1"});
assert.equal(first.prompt, "PC-1:~$");
assert.throws(() => terminal.createSession(state.devices["pc-1"], "windows"), /corresponde/);
assert.throws(() => terminal.createSession({}), /Equipamento/);
assert.throws(() => terminal.createSession(state.devices["pc-1"], null), /Profile inválido/);
for (const forbidden of ["config", "devices", "interfaces", "vlans", "arp", "mac", "routes", "labState"])
  assert.equal(Object.hasOwn(first, forbidden), false);
const result = terminal.execute(first, "help", frozen(state));
assert.equal(result.error, null);
assert.ok(result.output.length >= 8);
assert.match(result.output.join('\n'),/dig/);
assert.match(result.output[0], /PC-1 · Linux · modo exec/);
assert.deepEqual(first.history, [], "execute não muda a sessão de entrada");
assert.deepEqual(second.history, []);
first = result.session;
let next = terminal.execute(first, "show ip route", state);
assert.equal(next.error.code, "unknown-command"); first = next.session;
assert.equal(terminal.execute(first, "help extra", state).error.code, "unexpected-arguments");
assert.equal(terminal.execute(first, "help '", state).error.code, "unclosed-quote");
assert.deepEqual(terminal.execute(first, " ", state).session.history, first.history);
let moved = terminal.navigateHistory(first, "up", "rascunho");
assert.equal(moved.command, "show ip route");
moved = terminal.navigateHistory(moved.session, "up"); assert.equal(moved.command, "help");
moved = terminal.navigateHistory(moved.session, "up"); assert.equal(moved.command, "help");
moved = terminal.navigateHistory(moved.session, "down"); assert.equal(moved.command, "show ip route");
moved = terminal.navigateHistory(moved.session, "down"); assert.equal(moved.command, "rascunho");
assert.equal(terminal.navigateHistory(second, "up", "novo").command, "novo");
assert.throws(() => terminal.navigateHistory(first, "left"), /Direção/);
next = terminal.execute(first, "clear", state);
assert.equal(next.cleared, true); assert.deepEqual(next.session.output, []);
assert.deepEqual(next.session.history, ["help", "show ip route", "clear"]);
next = terminal.execute(next.session, "exit", state);
assert.equal(next.closed, true); assert.equal(next.session.mode, "closed"); assert.equal(next.session.context, null);
assert.equal(terminal.execute(next.session, "help", state).error.code, "session-closed");
assert.equal(terminal.createSession(state.devices["pc-1"]).closed, false);
assert.equal(JSON.stringify(state), before, "comandos genéricos não alteram a rede");

const registry = terminal.createRegistry();
assert.deepEqual(registry.available("pc", "linux", "exec").map(c => c.name), ["clear", "connect", "curl", "dhclient", "dig", "exit", "help", "hostname", "ip", "nslookup", "ping", "traceroute"]);
registry.register("pc", "linux", {name: "inspect", description: "Teste de consulta real", modes: ["exec"], execute: ({device, labState}) => ({output: [device.config.ip, String(labState.devices["pc-2"].config.gateway)]})});
registry.register("pc", "linux", {name: "enter", description: "Teste de contexto", modes: ["exec"], execute: ({device}) => ({mode: "config", context: {deviceId: device.id, interfaceId: device.interfaces[0]}, output: []})});
registry.register("pc", "linux", {name: "leave", description: "Teste de modo", modes: ["config"], execute: ({device}) => ({mode: "exec", context: {deviceId: device.id}, output: []})});
registry.register("pc", "linux", {name: "broken", description: "Teste de erro", modes: ["exec"], execute: () => { throw new Error("interno"); }});
registry.register("pc", "linux", {name: "async", description: "Teste de contrato síncrono", modes: ["exec"], execute: () => Promise.resolve({output: ["x"]})});
registry.register("pc", "linux", {name: "bad-context", description: "Sem estado paralelo", modes: ["exec"], execute: ({device}) => ({context: {deviceId: device.id, ip: "1.2.3.4"}})});
assert.throws(() => registry.register("pc", "cisco-ios", {}), /Profile/);
assert.throws(() => registry.register("*", "linux", {}), /Registry/);
assert.throws(() => registry.register("pc", "linux", {name: "inspect", description: "dup", modes: ["exec"], execute() {}}), /registrado/);
assert.throws(() => registry.register("pc", "linux", {name: "x"}), /Definição/);
assert.equal(registry.resolve("pc", "windows", "inspect"), undefined, "registry isola profiles");
assert.equal(registry.resolve("switch", "generic", "inspect"), undefined, "registry isola tipos");
const session = terminal.createSession(state.devices["pc-1"]);
assert.equal(terminal.execute(session, "inspect", state, registry).output[0], "192.168.10.10");
let updated = model.configure(state, "pc-1", {ip: "192.168.10.77"}).state;
updated = model.configure(updated, "pc-2", {gateway: "192.168.10.1"}).state;
assert.deepEqual(terminal.execute(session, "inspect", frozen(updated), registry).output, ["192.168.10.77", "192.168.10.1"]);
next = terminal.execute(session, "enter", updated, registry);
assert.equal(next.session.mode, "config"); assert.equal(next.session.context.interfaceId, "pc-1:eth0");
assert.equal(terminal.execute(next.session, "inspect", updated, registry).error.code, "wrong-mode");
assert.deepEqual(registry.available("pc", "linux", "config").map(c => c.name), ["leave"]);
next = terminal.execute(next.session, "leave", updated, registry); assert.equal(next.session.mode, "exec");
assert.equal(terminal.execute(session, "broken", state, registry).error.code, "execution-error");
assert.equal(terminal.execute(session, "async", state, registry).error.code, "execution-error");
assert.equal(terminal.execute(session, "bad-context", state, registry).error.code, "execution-error");
updated = model.renameDevice(updated, "pc-1", "Estação").state;
assert.equal(terminal.syncSession(session, updated).session.prompt, "Estação:~$");
updated = model.setProfile(updated, "pc-1", "windows").state;
next = terminal.execute(session, "help", updated, registry);
assert.equal(next.session.profileId, "windows"); assert.match(next.output[0], /Estação · Windows/);
const configSession = terminal.execute(session, "enter", state, registry).session;
assert.equal(terminal.syncSession(configSession, updated).session.mode, "exec", "troca de profile encerra contexto incompatível");
assert.equal(terminal.execute(session, "help", model.removeDevice(updated, "pc-1").state).error.code, "device-unavailable");
let bounded = session;
for (let i = 0; i < 150; i++) bounded = terminal.execute(bounded, "help", state).session;
assert.equal(bounded.history.length, terminal.LIMITS.history);
assert.equal(bounded.output.length, terminal.LIMITS.output);
assert.equal(second.output.length, 0, "outputs não atravessam sessões");
for (const type of ["pc", "switch", "router"]) for (const profile of profiles.list(type)) {
  const bench = model.addDevice(model.createEmpty(), type, profile.id).state;
  const device = Object.values(bench.devices)[0];
  const active = terminal.createSession(device);
  assert.equal(terminal.execute(active, "help", bench).error, null);
  if (profile.id === "cisco-ios") assert.equal(terminal.execute(active, "enable", bench).session.mode, "privileged");
  else assert.equal(terminal.execute(active, "enable", bench).error.code, "unknown-command");
}
console.log("Terminal Engine v1: parser, sessões, histórico, modos, contexto, registry e bancada real aprovados.");
